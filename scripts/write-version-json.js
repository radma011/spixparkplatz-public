#!/usr/bin/env node

/**
 * Source of truth: download-page/version.json
 * Syncs versionName / versionCode into:
 *  - src/constants/appVersion.generated.ts (in-app display)
 *  - android/app/build.gradle
 *  - ios MARKETING_VERSION / CURRENT_PROJECT_VERSION
 *  - package.json "version" (versionName only)
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const versionJsonPath = path.join(root, 'download-page/version.json');
const buildGradlePath = path.join(root, 'android/app/build.gradle');
const pbxprojPath = path.join(root, 'ios/spixparkplatz.xcodeproj/project.pbxproj');
const appVersionTsPath = path.join(root, 'src/constants/appVersion.generated.ts');
const packageJsonPath = path.join(root, 'package.json');

if (!fs.existsSync(versionJsonPath)) {
  console.error('Missing download-page/version.json');
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(versionJsonPath, 'utf8'));
const versionName = String(raw.versionName || '').trim();
const versionCode = Number(raw.versionCode);

if (!/^\d+\.\d+\.\d+/.test(versionName)) {
  console.error(`Invalid versionName in version.json: ${JSON.stringify(versionName)}`);
  process.exit(1);
}
if (!Number.isInteger(versionCode) || versionCode < 1) {
  console.error(`Invalid versionCode in version.json: ${JSON.stringify(raw.versionCode)}`);
  process.exit(1);
}

// Keep updatedAt fresh when syncing
const data = {
  versionName,
  versionCode,
  updatedAt: new Date().toISOString(),
};
fs.writeFileSync(versionJsonPath, JSON.stringify(data, null, 2) + '\n', 'utf8');
console.log('version.json:', data);

const appVersionTs = `/** Auto-generated by scripts/write-version-json.js – do not edit manually */
export const APP_VERSION_NAME = '${versionName}';
export const APP_VERSION_CODE = ${versionCode};
`;
fs.mkdirSync(path.dirname(appVersionTsPath), {recursive: true});
fs.writeFileSync(appVersionTsPath, appVersionTs, 'utf8');
console.log('Written appVersion.generated.ts');

let gradle = fs.readFileSync(buildGradlePath, 'utf8');
if (!/versionCode\s+\d+/.test(gradle) || !/versionName\s+["'][^"']+["']/.test(gradle)) {
  console.error('Could not find versionCode/versionName in android/app/build.gradle');
  process.exit(1);
}
gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${versionCode}`);
gradle = gradle.replace(/versionName\s+["'][^"']+["']/, `versionName "${versionName}"`);
fs.writeFileSync(buildGradlePath, gradle, 'utf8');
console.log('Updated android/app/build.gradle');

let pbx = fs.readFileSync(pbxprojPath, 'utf8');
if (!/MARKETING_VERSION = [^;]+;/.test(pbx) || !/CURRENT_PROJECT_VERSION = [^;]+;/.test(pbx)) {
  console.error('Could not find MARKETING_VERSION/CURRENT_PROJECT_VERSION in project.pbxproj');
  process.exit(1);
}
pbx = pbx.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${versionName};`);
pbx = pbx.replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${versionCode};`);
fs.writeFileSync(pbxprojPath, pbx, 'utf8');
console.log('Updated ios project.pbxproj');

const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
pkg.version = versionName;
fs.writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
console.log('Updated package.json version');

console.log(`Synced app version ${versionName} (${versionCode})`);
